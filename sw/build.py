"""
build.py - generate FIR test data, golden results and all program images.

  1. Designs a 16-tap low-pass FIR filter (windowed-sinc, Hamming window,
     cut-off 0.1 cycles/sample) and quantises it to Q15.
  2. Builds a 128-sample Q15 test signal: a low-frequency tone (kept by the
     filter) plus a high-frequency tone (removed by the filter).
  3. Computes the bit-exact golden output with the same arithmetic as the
     hardware:  y[n] = sat16( (sum h[k] x[n-k]) >> 15 )
  4. Writes sw/fir_data.inc and generates the fully unrolled FIR programs.
  5. Assembles every program with rvasm.py into build/.

Output: build/<prog>.imem.hex / .dmem.hex / .lst / .sym,
        build/fir_golden.hex, build/fir_signal.json, build/manifest.json
"""
import json
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import rvasm  # noqa: E402

BUILD = os.path.join(HERE, "..", "build")
GEN = os.path.join(HERE, "gen")

N = 128          # number of output samples
TAPS = 16        # filter length
FC = 0.10        # cut-off frequency (cycles / sample)
F_LOW, A_LOW = 0.015, 0.50     # wanted tone
F_HIGH, A_HIGH = 0.30, 0.30    # unwanted tone


def design_filter():
    n = np.arange(TAPS)
    m = (TAPS - 1) / 2.0
    h = 2 * FC * np.sinc(2 * FC * (n - m)) * np.hamming(TAPS)
    h = h / h.sum()                               # unity DC gain
    hq = np.round(h * 32768).astype(int)
    return h, [int(v) for v in hq]


def make_signal():
    n = np.arange(N)
    xf = A_LOW * np.sin(2 * math.pi * F_LOW * n) + A_HIGH * np.sin(2 * math.pi * F_HIGH * n)
    xq = np.round(xf * 32767).astype(int)
    return xf, [int(v) for v in xq]


def golden(x, h):
    y = []
    for n in range(N):
        acc = 0
        for k in range(TAPS):
            if n - k >= 0:
                acc += h[k] * x[n - k]
        v = acc >> 15                              # arithmetic shift (floor)
        y.append(max(-32768, min(32767, v)))
    return y


def write_data_inc(x, h):
    pad = [0] * (TAPS - 1) + x
    hrev = list(reversed(h))
    lines = ["# generated by build.py - do not edit",
             ".equ N, %d" % N, ".equ TAPS, %d" % TAPS, "", ".data", ".align 2", "x_pad:"]
    for i in range(0, len(pad), 16):
        lines.append("    .half " + ", ".join(str(v) for v in pad[i:i + 16]))
    lines += [".align 2", "h_rev:"]
    for i in range(0, TAPS, 16):
        lines.append("    .half " + ", ".join(str(v) for v in hrev[i:i + 16]))
    lines += [".align 2", "y:", "    .space %d" % (2 * N), ""]
    with open(os.path.join(HERE, "fir_data.inc"), "w") as f:
        f.write("\n".join(lines))


def gen_mac_unrolled():
    """Fully unrolled inner loop: 3 instructions per tap (lh, lh, mac)."""
    L = ["# generated by build.py: FIR with MAC instructions, inner loop unrolled",
         '.include "../fir_data.inc"', ".text",
         "start:", "    la s0, x_pad", "    la s1, h_rev", "    la s2, y", "    li s3, N", "outer:"]
    for k in range(0, TAPS, 2):
        L += ["    lh t3, %d(s0)" % (2 * k), "    lh t4, %d(s1)" % (2 * k),
              "    lh t5, %d(s0)" % (2 * k + 2), "    lh t6, %d(s1)" % (2 * k + 2),
              "    %s x0, t3, t4" % ("mul.acc" if k == 0 else "mac"),
              "    mac x0, t5, t6"]
    L += ["    rdacc.q15 a2", "    addi s0, s0, 2", "    addi s3, s3, -1",
          "    sh a2, 0(s2)", "    addi s2, s2, 2", "    bnez s3, outer",
          "    li a0, 0x600D", "    ecall", ""]
    return "\n".join(L)


def gen_rv32im_unrolled():
    """Fully unrolled RV32IM baseline: 8 instructions per tap."""
    L = ["# generated by build.py: FIR in RV32IM, inner loop unrolled",
         '.include "../fir_data.inc"', ".text",
         "start:", "    la s0, x_pad", "    la s1, h_rev", "    la s2, y", "    li s3, N",
         "    li a5, 32767", "    li a6, -32768", "    li a7, -1", "outer:",
         "    li s4, 0", "    li s5, 0", "    li a4, 0"]
    for k in range(TAPS):
        L += ["    lh t3, %d(s0)" % (2 * k), "    lh t4, %d(s1)" % (2 * k),
              "    add s5, s5, a4",            # carry of the previous tap
              "    mul a2, t3, t4", "    mulh a3, t3, t4",
              "    add s4, s4, a2", "    sltu a4, s4, a2", "    add s5, s5, a3"]
    L += ["    add s5, s5, a4",
          "    srli t5, s4, 15", "    slli t6, s5, 17", "    or t5, t5, t6", "    srai t6, s5, 15",
          "    bltz t6, neg", "    bnez t6, satpos", "    bltu a5, t5, satpos", "    j store",
          "neg:", "    bne t6, a7, satneg", "    bltu t5, a6, satneg", "    j store",
          "satpos:", "    mv t5, a5", "    j store",
          "satneg:", "    mv t5, a6",
          "store:", "    sh t5, 0(s2)", "    addi s2, s2, 2", "    addi s0, s0, 2",
          "    addi s3, s3, -1", "    bnez s3, outer",
          "    li a0, 0x600D", "    ecall", ""]
    return "\n".join(L)


def main():
    os.makedirs(BUILD, exist_ok=True)
    os.makedirs(GEN, exist_ok=True)

    hf, h = design_filter()
    xf, x = make_signal()
    y = golden(x, h)
    write_data_inc(x, h)

    with open(os.path.join(GEN, "fir_mac_unrolled.s"), "w") as f:
        f.write(gen_mac_unrolled())
    with open(os.path.join(GEN, "fir_rv32im_unrolled.s"), "w") as f:
        f.write(gen_rv32im_unrolled())

    with open(os.path.join(BUILD, "fir_golden.hex"), "w") as f:
        for v in y:
            f.write("%04x\n" % (v & 0xFFFF))

    # floating-point reference of the ideal filter (for plots only)
    yf = np.convolve(xf, hf)[:N]
    with open(os.path.join(BUILD, "fir_signal.json"), "w") as f:
        json.dump({"N": N, "TAPS": TAPS, "FC": FC, "x": x, "h": h, "golden": y,
                   "x_float": list(map(float, xf)), "y_float": list(map(float, yf)),
                   "h_float": list(map(float, hf)),
                   "f_low": F_LOW, "f_high": F_HIGH}, f)

    programs = [
        ("isa_test", os.path.join(HERE, "isa_test.s"), False),
        ("fir_mac_loop", os.path.join(HERE, "fir_mac_loop.s"), True),
        ("fir_rv32im_loop", os.path.join(HERE, "fir_rv32im_loop.s"), True),
        ("fir_mac_unrolled", os.path.join(GEN, "fir_mac_unrolled.s"), True),
        ("fir_rv32im_unrolled", os.path.join(GEN, "fir_rv32im_unrolled.s"), True),
    ]
    manifest = []
    for name, src, is_fir in programs:
        p = rvasm.assemble_file(src)
        prefix = os.path.join(BUILD, name)
        p.write(prefix)
        rel = os.path.relpath(prefix, os.path.join(HERE, "..")).replace(os.sep, "/")
        entry = {"name": name, "imem": rel + ".imem.hex", "dmem": rel + ".dmem.hex",
                 "n_instr_static": len(p.text)}
        if is_fir:
            entry.update({"golden": "build/fir_golden.hex",
                          "yaddr": p.symbols["y"], "nout": N})
        manifest.append(entry)
        print("%-22s %4d instructions  %5d data bytes" % (name, len(p.text), len(p.data)))
    with open(os.path.join(BUILD, "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)
    print("filter taps (Q15):", h, " sum =", sum(h))


if __name__ == "__main__":
    main()
